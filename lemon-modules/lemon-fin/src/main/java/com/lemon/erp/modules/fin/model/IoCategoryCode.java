package com.lemon.erp.modules.fin.model;

/**
 * 内置收支类别的标识（fin_io_category.code）：业务单据自动生成费用支出单时按标识取类别，这些类别不能删除、不能改方向，名称和科目可以修改
 */
public enum IoCategoryCode {
    /** 销售运费：销售出库本公司承担、现付的运费（默认科目销售费用 6601） */
    SALES_FREIGHT,
    /** 代垫运费：销售出库、采购退货替往来单位垫付、现付给承运商的运费（默认科目其他应收款 1221，由往来单位的代垫运费单据冲平） */
    FREIGHT_ADVANCE,
    /** 调拨费用：调拨单的配送费现付给承运商（默认科目销售费用 6601，issue #104） */
    TRANSFER_FEE,
    /** 零售收入（收入）：门店日结时按结算账户汇总当日 POS 收款生成其他收入单（默认科目主营业务收入 6001，含税金额） */
    RETAIL_SALES,
    /** 零售退款（支出）：门店日结时按结算账户汇总当日 POS 退款生成费用支出单（默认科目主营业务收入 6001，冲减收入） */
    RETAIL_REFUND,
    /** 会员储值（收入）：门店日结时按结算账户汇总当日储值充值收款生成其他收入单（默认科目预收账款 2203，负债）；日结凭证中储值消费 借 该科目 / 贷 零售收入的科目 */
    MEMBER_TOPUP,
    /** 储值赠送（支出）：只用于取科目（默认销售费用 6601），门店日结凭证 借 该科目 / 贷 会员储值的科目，不生成收支单 */
    MEMBER_BONUS
}
